#!/usr/bin/env node
// Generates harness/claude (a Claude Code plugin + marketplace) from skills/; the output is committed.
import * as fs from "node:fs";
import * as path from "node:path";
import { listSkills } from "../src/skills.ts";

const PKG = path.resolve(import.meta.dirname, "..");

export function pluginFiles(pkgDir = PKG): Record<string, string> {
  const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, "package.json"), "utf8"));
  const skills = listSkills(path.join(pkgDir, "skills"));
  const description = "Test a change with the repo's own tests through witness: plan the expected behaviors, write tests, run them on a booted app, and triage setups that give no answer.";
  const files: Record<string, string> = {
    ".claude-plugin/plugin.json": JSON.stringify({ name: "witness", version: pkg.version, description, author: { name: "Modelcode" }, keywords: ["testing", "verification", "agents"] }, null, 2) + "\n",
    ".claude-plugin/marketplace.json":
      JSON.stringify({ name: "witness-local", description: "Local marketplace for the witness plugin", owner: { name: "Modelcode" }, plugins: [{ name: "witness", source: "./", description, version: pkg.version }] }, null, 2) + "\n",
    "README.md": [
      "# witness plugin (generated)",
      "",
      "Generated by `npm run build:plugin` from `packages/witness/skills/`; do not edit by hand.",
      "",
      `Skills: ${skills.map((s) => `\`witness:${s.name}\``).join(", ")}. Start with \`witness:test-change\`, which plans the expected behaviors of a change, writes tests in the repo's own framework, runs them through witness and triages runs that could not give an answer.`,
      "",
      "The skills call the `witness` command, which must be on PATH (see packages/witness/README.md).",
      "",
      "Install from this folder:",
      "",
      "```",
      "claude plugin marketplace add <path to>/packages/witness/harness/claude",
      "claude plugin install witness@witness-local",
      "```",
      "",
      "Other agents: `witness skills install --dir <their skills folder>`.",
      "",
    ].join("\n"),
  };
  for (const s of skills) for (const f of fs.readdirSync(s.dir)) files[`skills/${path.basename(s.dir)}/${f}`] = fs.readFileSync(path.join(s.dir, f), "utf8");
  return files;
}

export function buildPlugin(out = path.join(PKG, "harness", "claude"), pkgDir = PKG) {
  fs.rmSync(out, { recursive: true, force: true });
  for (const [rel, content] of Object.entries(pluginFiles(pkgDir))) {
    fs.mkdirSync(path.dirname(path.join(out, rel)), { recursive: true });
    fs.writeFileSync(path.join(out, rel), content);
  }
  return out;
}

const self = process.argv[1] ? fs.realpathSync(process.argv[1]) : "";
if (self.endsWith("build-plugin.ts")) process.stderr.write(`wrote ${path.relative(process.cwd(), buildPlugin()) || "."}\n`);
